#!/usr/bin/env python3
"""Write pages-sitemap.xml: every page in this repo, at its gooey.ai URL.

The list is found, not kept by hand: every index.html outside drafts and
templates is a page, and its URL is the canonical link that scripts/seo.py
wrote into it. So a new language, model, research or hand-written page lands
in the sitemap as soon as it is built.

<lastmod> is the page's own dateModified (its JSON-LD, which comes from the
evaluation snapshot or scripts/static_seo.json). A page with no such date gets
no <lastmod> rather than a guessed one, since search engines stop trusting a
sitemap whose dates are wrong.

A page fails the build if it has no canonical link, or if its canonical URL
is not the gooey.ai URL of the folder it lives in. A page marked noindex is
left out.

The gooey.ai sitemap (gooey.ai/sitemap.xml) belongs to the Gooey app
(gooey-server). It should list this file in its sitemap index or robots.txt.

Usage:
  python3 scripts/build_sitemap.py          # rewrite pages-sitemap.xml
  python3 scripts/build_sitemap.py --check  # fail if it is missing or stale
"""
from __future__ import annotations

import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "pages-sitemap.xml"
SITE = "https://gooey.ai/"
SKIP = {"drafts", "node_modules", "_src", ".git", ".claude", ".github", "scripts"}

CANONICAL = re.compile(r'<link rel="canonical" href="([^"]+)"')
MODIFIED = re.compile(r'"dateModified": "(\d{4}-\d{2}-\d{2})')
NOINDEX = re.compile(r'<meta name="robots" content="[^"]*noindex', re.I)


def pages() -> list[tuple[str, str | None]]:
    found, errors = [], []
    for f in sorted(ROOT.rglob("index.html")):
        rel = f.relative_to(ROOT)
        if SKIP & set(rel.parts[:-1]):
            continue
        html = f.read_text(encoding="utf-8")
        if NOINDEX.search(html):
            continue
        folder = rel.parent.as_posix()
        expected = SITE if folder == "." else f"{SITE}{folder}/"
        m = CANONICAL.search(html)
        if not m:
            errors.append(f"{rel}: no canonical link (add the page to scripts/static_seo.json or its builder)")
            continue
        if m.group(1) != expected:
            errors.append(f"{rel}: canonical is {m.group(1)}, expected {expected}")
            continue
        mod = MODIFIED.search(html)
        found.append((expected, mod.group(1) if mod else None))
    if errors:
        sys.exit("sitemap: " + "\n  ".join(["pages with a wrong or missing canonical URL:", *errors]))
    return sorted(found)


def render(entries: list[tuple[str, str | None]]) -> str:
    rows = []
    for loc, mod in entries:
        row = f"  <url>\n    <loc>{escape(loc)}</loc>\n"
        if mod:
            row += f"    <lastmod>{mod}</lastmod>\n"
        rows.append(row + "  </url>\n")
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            "<!-- Generated by scripts/build_sitemap.py. Do not edit. -->\n"
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + "".join(rows) + "</urlset>\n")


def main() -> None:
    entries = pages()
    xml = render(entries)
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != xml:
            sys.exit(f"{OUT.name} is missing or stale: run python3 scripts/build_sitemap.py")
        print(f"ok: {OUT.name} lists all {len(entries)} page(s)")
        return
    OUT.write_text(xml, encoding="utf-8")
    dated = sum(1 for _, m in entries if m)
    print(f"wrote {OUT.name}: {len(entries)} page(s), {dated} with a last-modified date")


if __name__ == "__main__":
    main()
