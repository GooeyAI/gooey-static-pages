#!/usr/bin/env python3
"""Search and sharing tags for the hand-written pages (sovereignty, ecocost, research, lokalibrary, ...).

    python3 scripts/build_static_seo.py            # rewrite the tags in every page's <head>
    python3 scripts/build_static_seo.py --check    # fail if a page's tags are stale, or a page has none

The pages themselves stay hand-written; only the block of tags at the top of <head> is generated, from
scripts/static_seo.json, by the same code as the generated pages (scripts/seo.py): title, description, canonical
gooey.ai URL, Open Graph and X tags, icons, JSON-LD and a 1200x630 share card. The block sits between two comments:

    <!-- SEO: generated by scripts/build_static_seo.py from scripts/static_seo.json. Edit those, not this block. -->
    ...
    <!-- /SEO -->

so edit the JSON, not the block. Any title, description, og:, twitter: or icon tag found elsewhere in <head> is
removed, so a page can't carry two disagreeing sets.

A new top-level page must be added to static_seo.json (the --check fails until it is). Its entry:

    name          short name for breadcrumbs ("EcoCost")
    title         at most 60 characters, ending " — Gooey.AI" when that fits
    description   120-155 characters
    type          "Article" (a paper, proposal or essay), "WebPage", or "CollectionPage" (a hub)
    section, published, updated, authors [[name, url], ...]     Articles: label, ISO dates, bylines
    parent        [name, folder] when the page sits under another one (sovereignty under research)
    list          "papers": the hub lists the research paper pages (research only)
    card          {"eyebrow", "title", and "banner": image path (3:1 shows whole; "position" to aim a crop)
                   or "wall": "venues" for the research venue logos}
    image_alt     what the share card shows, for screen readers and the og:image:alt tag

After editing, run this script, then python3 scripts/build_og_images.py to render any changed card.
"""

from __future__ import annotations

import csv
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import seo  # noqa: E402

ROOT = seo.ROOT
CONFIG = ROOT / "scripts" / "static_seo.json"
BEGIN = "<!-- SEO: generated by scripts/build_static_seo.py from scripts/static_seo.json. Edit those, not this block. -->"
END = "<!-- /SEO -->"
# Top-level folders whose pages other builders write (build_language_pages.py, build_model_pages.py)
GENERATED = {"language", "models"}
SKIP = {"drafts", "scripts", "node_modules"}
SEO_TAG = re.compile(
    r"[ \t]*(?:<title>.*?</title>"
    r'|<meta\s+(?:name|property)="(?:description|robots|theme-color|og:[^"]*|twitter:[^"]*|article:[^"]*)"[^>]*>'
    r'|<link\s+rel="(?:canonical|icon|shortcut icon|apple-touch-icon)"[^>]*>'
    r'|<script type="application/ld\+json">.*?</script>)[ \t]*\n', re.S)
BLOCK = re.compile(r"[ \t]*" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"[ \t]*\n", re.S)


def venues() -> list[str]:
    """Local venue logos from the research page's own list (research/data/Papers.csv), in list order."""
    out = []
    with (ROOT / "research" / "data" / "Papers.csv").open(encoding="utf-8") as f:
        for row in csv.DictReader(f):
            logo = (row.get("logo") or "").strip()
            if row.get("hidden", "").strip() or not logo or logo.startswith("http"):
                continue
            path = f"research/{logo}"
            if (ROOT / path).is_file() and path not in out:
                out.append(path)
    return out


def paper_pages() -> list[dict]:
    """The research paper pages, as build_papers.py writes them (a paper needs its hosted PDF to get a page)."""
    from papers_content import PAPERS
    return [{"@type": "ListItem", "position": i + 1, "name": p["title"], "url": seo.url(f"research/papers/{p['slug']}")}
            for i, p in enumerate(q for q in PAPERS if (ROOT / "research" / "pdf" / f"{q['slug']}.pdf").exists())]


def card_for(c: dict) -> dict:
    card = {"eyebrow": c["eyebrow"], "title": c["title"]}
    if c.get("banner"):
        card["visual"] = {"kind": "banner", "src": c["banner"], **({"position": c["position"]} if c.get("position") else {})}
    if c.get("wall") == "venues":
        card["wall"] = {"label": "Papers and talks at", "logos": venues()[:9],
                        "byline": "Gooey.AI with the Royal College of Art",
                        "marks": ["research/assets/gooey-robot.png", "research/images/orgs/rca.png"]}
    return card


def tags(folder: str, p: dict) -> str:
    image = seo.og_image(folder, card_for(p["card"]), p["image_alt"])
    u = seo.url(folder)
    short = p["title"].removesuffix(" — Gooey.AI")
    trail = [("Home", seo.SITE)] + ([(p["parent"][0], seo.url(p["parent"][1]))] if p.get("parent") else []) + [(p["name"], None)]
    graph = [seo.ORG]
    if p["type"] == "Article":
        art = {"@type": "Article", "@id": u + "#article", "headline": short, "description": p["description"], "url": u,
               "mainEntityOfPage": u, "inLanguage": "en", "publisher": {"@id": seo.ORG["@id"]},
               "image": {"@type": "ImageObject", "url": image[0], "width": 1200, "height": 630},
               "author": ([{"@type": "Person", "name": n, "url": link} for n, link in p["authors"]] if p.get("authors")
                          else {"@id": seo.ORG["@id"]})}
        for key, prop in (("section", "articleSection"), ("published", "datePublished"), ("updated", "dateModified")):
            if p.get(key):
                art[prop] = p[key]
        graph.append(art)
    else:
        page = seo.webpage(folder, p["title"], p["description"], image, kind=p["type"])
        if p.get("list") == "papers":
            page["mainEntity"] = {"@type": "ItemList", "itemListElement": paper_pages()}
        graph.append(page)
    graph.append(seo.breadcrumbs(folder, trail))
    article = {"section": p.get("section"), "published": p.get("published"), "modified": p.get("updated")}
    block = seo.head(path=folder, title=p["title"], description=p["description"], og_title=short,
                     og_type="article" if p["type"] == "Article" else "website", image=image, graph=graph,
                     article=article if p["type"] == "Article" else None)
    return f"    {BEGIN}\n{block}    {END}\n"


def inject(page_html: str, block: str, where: str) -> str:
    """Put the block where the old one (or the first old SEO tag) was, and drop every other SEO tag in <head>."""
    head, sep, rest = page_html.partition("</head>")
    if not sep:
        raise SystemExit(f"{where}: no </head>")
    m = BLOCK.search(head) or SEO_TAG.search(head)
    if not m:
        m = re.search(r"[ \t]*<!-- GOOEY-BASE-HREF -->[ \t]*\n", head)
        if not m:
            raise SystemExit(f"{where}: no <title> or GOOEY-BASE-HREF comment to put the SEO block after")
        pos = m.end()
    else:
        pos = m.start()
    before, after = SEO_TAG.sub("", head[:pos]), SEO_TAG.sub("", BLOCK.sub("", head[pos:]))
    return before + block + after + sep + rest


def pages() -> dict[pathlib.Path, str]:
    """Every configured page with its tags rewritten: path -> HTML."""
    config = json.loads(CONFIG.read_text(encoding="utf-8"))
    out = {}
    for folder, p in config.items():
        f = ROOT / folder / "index.html"
        if not f.exists():
            raise SystemExit(f"static_seo.json lists {folder!r}, but {folder}/index.html does not exist")
        out[f] = inject(f.read_text(encoding="utf-8"), tags(folder, p), f"{folder}/index.html")
    return out


def unconfigured() -> list[str]:
    """Top-level pages that no builder gives SEO tags to."""
    config = json.loads(CONFIG.read_text(encoding="utf-8"))
    return sorted(d.name for d in ROOT.iterdir()
                  if d.is_dir() and (d / "index.html").exists() and not d.name.startswith(".")
                  and d.name not in SKIP | GENERATED and d.name not in config)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    problems = [f"{name}/index.html has no entry in scripts/static_seo.json; add one (see this script's docstring)"
                for name in unconfigured()]
    for f, html in pages().items():
        rel = f.relative_to(ROOT)
        if check:
            if f.read_text(encoding="utf-8") != html:
                problems.append(f"{rel}: SEO tags are stale; run python3 scripts/build_static_seo.py")
        else:
            if f.read_text(encoding="utf-8") != html:
                f.write_text(html, encoding="utf-8")
                print(f"wrote {rel}")
    if problems:
        print("\n".join(problems))
        return 1
    if check:
        print(f"ok: {len(pages())} hand-written page(s) carry current SEO tags")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
